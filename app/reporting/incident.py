"""Incident post-mortem and root-cause analysis report generator."""

from datetime import UTC, datetime


def generate_post_mortem(
    title: str,
    summary: str,
    root_cause: str,
    severity: str = "P2 - Major",
    namespace: str = "default",
    impacted_services: list[str] | None = None,
    timeline: list[dict] | None = None,
    evidence: list[str] | None = None,
    remediation_actions: list[str] | None = None,
    action_items: list[str] | None = None,
    author: str = "KubePilot AI Operations Agent",
) -> str:
    """Generate a structured, professional Markdown post-mortem document adhering to SRE best practices."""
    now_str = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    services_str = ", ".join(impacted_services) if impacted_services else "N/A"

    doc = [
        f"# Incident Post-Mortem: {title}",
        "",
        "| Attribute | Value |",
        "|---|---|",
        f"| **Date / Time** | {now_str} |",
        f"| **Severity** | `{severity}` |",
        f"| **Namespace** | `{namespace}` |",
        f"| **Impacted Workload(s)** | `{services_str}` |",
        f"| **Generated By** | {author} |",
        "| **Status** | Resolved / Mitigated |",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        "",
        summary.strip(),
        "",
        "## 2. Root Cause Analysis",
        "",
        root_cause.strip(),
        "",
        "## 3. Incident Timeline",
        "",
    ]

    if timeline:
        doc.append("| Timestamp | Component | Event / Observation |")
        doc.append("|---|---|---|")
        for item in timeline:
            ts = item.get("time", "T-0")
            comp = item.get("component", "system")
            desc = item.get("description", "")
            doc.append(f"| {ts} | `{comp}` | {desc} |")
        doc.append("")
    else:
        doc.append(f"- **{now_str}** - Anomaly detected and diagnosed by KubePilot.")
        doc.append(f"- **{now_str}** - Root cause isolated to `{services_str}`.")
        doc.append("")

    doc.append("## 4. Evidence & Observability Signals")
    doc.append("")
    if evidence:
        for ev in evidence:
            doc.append(f"- {ev}")
    else:
        doc.append("- Diagnostics collected via Kubernetes API, container logs, and telemetry.")
    doc.append("")

    doc.append("## 5. Remediation & Recovery Actions")
    doc.append("")
    if remediation_actions:
        for act in remediation_actions:
            doc.append(f"- [x] {act}")
    else:
        doc.append("- [x] Workload inspected and operational remediation applied.")
    doc.append("")

    doc.append("## 6. Preventative Action Items & Recommendations")
    doc.append("")
    if action_items:
        doc.append("| Priority | Action Item | Type |")
        doc.append("|---|---|---|")
        for item in action_items:
            doc.append(f"| P1 | {item} | Prevention |")
    else:
        doc.append("| Priority | Action Item | Type |")
        doc.append("|---|---|---|")
        doc.append("| P1 | Configure proper container resource requests and limits | Configuration |")
        doc.append(
            "| P2 | Add automated alert for recurring container restarts and CrashLoopBackOff | Monitoring |"
        )
        doc.append("| P2 | Review CI/CD health checks and readiness probes before routing | QA |")
    doc.append("")
    doc.append("---")
    doc.append(f"*Report compiled by KubePilot on {now_str}*")

    return "\n".join(doc)
